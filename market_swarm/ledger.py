"""The dataset writer: one header line, then one compact JSON object per trade action.

The label is enforced, not decorative. A `TradeRow` carries `synthetic=True`, the writer
refuses to write a row where it is anything else, and the header that every file starts
with says `SYNTHETIC DATA` and carries a disclaimer. A file this module writes therefore
cannot be mistaken for real market pricing by someone who opens it.

The file is line-delimited JSON so a killed run leaves a readable file: each `write` emits
one complete line and flushes, so the last line on disk is either a whole record or no
line at all. `seq` is stamped by the writer from 1, so it is monotone whatever the caller
put in the row, and `ts` is normalised to ISO-8601 UTC with a `Z` suffix.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, fields
from datetime import datetime, timezone
from pathlib import Path
from typing import Mapping

from .config import PROGRAMS

STATUSES = frozenset({"ok", "refused", "error", "skipped"})
CHAINS = frozenset({"local-validator", "devnet", "simulated"})

#: The closed set of values the `action` column may take. `buy`, `list` and `resell` are the
#: three intents a policy can return. `refuse` is a decision that was **not** taken: a live
#: policy declining to decide because its own cap is spent. It has no price and no move, and
#: it gets its own value so no reader can count it as a purchase. `unknown` is an intent whose
#: action was unreadable; the row's rationale quotes what it said.
ACTIONS = frozenset({"buy", "list", "refuse", "resell", "unknown"})

SCHEMA_VERSION = 1

LABEL = "SYNTHETIC DATA: market_swarm agent actions, generated, not real market pricing"
DISCLAIMER = (
    "Generated by agents against a local validator or in simulation. This is NOT "
    "evidence of real market pricing and must not be used to estimate real prices."
)

# The header every dataset file starts with. Callers copy it (`dict(LEDGER_HEADER)`) and
# add their run id; the writer checks the required literals are still present, so a
# hand-built header cannot drop the label.
LEDGER_HEADER = {
    "record": "header",
    "synthetic": True,
    "schema_version": SCHEMA_VERSION,
    "label": LABEL,
    "disclaimer": DISCLAIMER,
}


@dataclass(frozen=True)
class TradeRow:
    """One action, flattened: no chain types, no handles, only JSON values.

    `status` is one of `STATUSES`, `chain` is one of `CHAINS`, `program` is one of `PROGRAMS`,
    and `synthetic` is always True. `seq` and `ts` are present on the row for inspection, but
    `LedgerWriter.write` stamps the values it actually writes.
    """

    run_id: str
    seq: int
    ts: str
    event_id: str
    mode: str

    agent_id: str
    action: str
    ticket_id: str | None
    from_wallet: str | None
    to_wallet: str | None
    price_lamports: int | None
    face_lamports: int
    cap_bps: int
    ceiling_lamports: int
    markup_bps: int | None
    status: str
    error_code: int | None
    signature: str | None
    slot: int | None
    block_time: int | None
    latency_ms: int | None
    hop_index: int | None
    budget_before: int
    budget_after: int
    chain: str
    #: Which of the two `cap_hook` programs produced this row: `"v1"` or `"v2"`. On the row and
    #: not only in the header for the same reason `chain` is: a v1 row and a v2 row answer
    #: different questions -- v2 has a floor, a jurisdiction and a hold clock that v1 has no bytes
    #: for -- so a dataset that silently mixed them would be two datasets wearing one name. The
    #: writer refuses a value outside `PROGRAMS`, and `datasets.verify_dataset` refuses a row whose
    #: program disagrees with the header it sits under.
    program: str
    rationale: str

    # The two fields a resale needs and a single price cannot carry. `bid_lamports` is the
    # opposing order this row was matched against (None for a primary buy, a listing or a
    # refusal), so (ask, bid) survives into the dataset and a table of executed trades can
    # be separated from a table of asks nobody met. `lot_price_lamports` is what the seller
    # paid, which is the only way a realised markup can be computed later without joining
    # rows, and joining rows is how a dataset loses its provenance.
    bid_lamports: int | None = None
    lot_price_lamports: int | None = None

    # Where in the horizon this row sits. The programme prices a ticket against its remaining
    # time-to-event, so "markup by time-to-event" has to be computable from the dataset alone.
    # Without these, two rows from the same round could only be joined on `ts`, which is a
    # wall clock and not the horizon.
    round: int | None = None
    rounds_left: int | None = None

    # The artist fee, which is an event-level rule and a per-row fact. `artist_fee_bps` is the
    # event's rate, so the fee can be recomputed from `price_lamports` alone and a reader never
    # has to join rows to learn what rate applied. `fee_lamports` is what the seller actually
    # paid on the sale this row records: the fee on an executed trade, 0 on a row that records
    # a sale the chain refused or never ran, and `None` on an event with no fee policy at all.
    # Both default, and both sit with the other optional columns rather than after `synthetic`,
    # which stays the last field: it is the label the writer checks, not a fact about a trade.
    # A row from a config that names no fee therefore carries `None` in both and is otherwise
    # the row it always was.
    fee_lamports: int | None = None
    artist_fee_bps: int | None = None

    # The flip tax, which is an event-level rule and a per-row fact in the same way the fee is,
    # and deliberately a separate set of columns: the two can disagree, and a reader checking one
    # must not have to trust the other. `flip_tax_bps` is the rate this row was assessed at (the
    # schedule prices it from the hold, so it is a fact about the row and not only about the
    # event), `held_seconds` is the hold that produced it (`None` when the record's clock was
    # never written, which is charged the full rate), and `flip_tax_lamports` is what actually
    # moved: the tax on an executed resale, 0 on a sale that did not land or that did not carry
    # the tax at all, and `None` on an event with no tax policy. All three default, and a row from
    # a config that names no tax carries `None` in all three and is otherwise the row it always
    # was.
    flip_tax_lamports: int | None = None
    flip_tax_bps: int | None = None
    held_seconds: int | None = None

    synthetic: bool = True

    def as_dict(self) -> dict:
        """Every field as a plain dict, in declaration order, ready for `json.dumps`."""
        return {field.name: getattr(self, field.name) for field in fields(self)}


def _check_header(header: Mapping) -> dict:
    """Validate the required header literals and return a mutable copy."""
    if not isinstance(header, Mapping):
        raise TypeError("header: expected a mapping")
    checked = dict(header)

    if checked.get("record") != "header":
        raise ValueError("header.record: must be the literal 'header'")
    if checked.get("synthetic") is not True:
        raise ValueError("header.synthetic: must be True")
    if checked.get("schema_version") != SCHEMA_VERSION:
        raise ValueError(f"header.schema_version: must be {SCHEMA_VERSION}")
    label = checked.get("label")
    if not isinstance(label, str) or not label.startswith("SYNTHETIC DATA"):
        raise ValueError("header.label: must be a string starting 'SYNTHETIC DATA'")
    disclaimer = checked.get("disclaimer")
    if not isinstance(disclaimer, str):
        raise ValueError("header.disclaimer: must be a string")
    for phrase in ("local validator", "simulation", "NOT evidence of real market pricing"):
        if phrase not in disclaimer:
            raise ValueError(
                f"header.disclaimer: must say the data is generated against a local "
                f"validator or in simulation and is not real market pricing "
                f"(missing {phrase!r})"
            )
    return checked


def _stamp_ts(ts: str | None) -> str:
    """An ISO-8601 UTC timestamp ending in `Z`.

    A row that already carries a `Z` timestamp is left exactly as it is. A naive
    timestamp is read as UTC and given the suffix; an offset is converted to UTC. A row
    with no timestamp is stamped with now, which is the only clock read in this module
    and is never reached by a test that supplies its own `ts`.
    """
    if not ts:
        return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    if ts.endswith("Z"):
        return ts
    try:
        parsed = datetime.fromisoformat(ts)
    except ValueError as exc:
        raise ValueError(f"ts: not an ISO-8601 timestamp: {ts!r}") from exc
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc).isoformat().replace("+00:00", "Z")


class LedgerWriter:
    """Writes one dataset file: header first, then one JSON object per action.

    Opening a path truncates it. A run owns its dataset file, and the header has to be
    the first line, so appending to a file this writer did not create is not offered.
    """

    def __init__(self, path: Path, *, header: Mapping) -> None:
        self._path = Path(path)
        self._header = _check_header(header)
        self._header.setdefault(
            "created_at",
            datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
        )
        self._seq = 0
        self._closed = False
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._handle = self._path.open("w", encoding="utf-8", newline="\n")
        self._write_line(self._header)

    def _write_line(self, payload: Mapping) -> None:
        """One complete line, then a flush, so a kill cannot leave half a record."""
        line = json.dumps(dict(payload), separators=(",", ":"), ensure_ascii=False)
        self._handle.write(line + "\n")
        self._handle.flush()

    def write(self, row: TradeRow) -> None:
        """Write one row, stamping `seq` and normalising `ts`.

        Refuses (before writing anything) a row that is not `TradeRow`, a row whose
        `synthetic` is not `True`, and a row whose `status`, `action`, `chain` or `program` is
        outside the closed vocabulary.
        """
        if self._closed:
            raise ValueError("ledger is closed; no further rows can be written")
        if not isinstance(row, TradeRow):
            raise TypeError(f"row: expected TradeRow, got {type(row).__name__}")
        if row.synthetic is not True:
            raise ValueError("row.synthetic: must be True; this dataset is synthetic only")
        if row.status not in STATUSES:
            raise ValueError(
                f"row.status: expected one of {sorted(STATUSES)}, got {row.status!r}"
            )
        if row.action not in ACTIONS:
            raise ValueError(
                f"row.action: expected one of {sorted(ACTIONS)}, got {row.action!r}"
            )
        if row.chain not in CHAINS:
            raise ValueError(
                f"row.chain: expected one of {sorted(CHAINS)}, got {row.chain!r}"
            )
        if row.program not in PROGRAMS:
            raise ValueError(
                f"row.program: expected one of {sorted(PROGRAMS)}, got {row.program!r}"
            )

        payload = row.as_dict()
        payload["seq"] = self._seq + 1
        payload["ts"] = _stamp_ts(row.ts)
        # Serialise before touching the file: a row that cannot be represented must not
        # leave anything behind.
        json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
        self._write_line(payload)
        self._seq += 1

    def close(self) -> None:
        """Flush and close. Idempotent."""
        if self._closed:
            return
        self._handle.flush()
        self._handle.close()
        self._closed = True

    def __enter__(self) -> "LedgerWriter":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        self.close()
